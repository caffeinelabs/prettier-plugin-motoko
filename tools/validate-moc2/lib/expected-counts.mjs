/**
 * Regenerate this module's data from a live census. Called only by
 * `bin/census.mjs --write-expected`, i.e. after a deliberate re-pin — never during a normal check run,
 * so the checked-in numbers can only change when a human asks for it.
 *
 * It *splices* the `export const EXPECTED_UNITS = { ... }` block in this very file rather than
 * regenerating the whole module, so the header comment, this function and any later edit survive the
 * rewrite byte-for-byte. Everything before the `export` and everything from the closing `};` on stays
 * put; only the object literal is replaced.
 */
export function writeExpected({ oracle, full }) {
    const here = new URL('./expected-counts.mjs', import.meta.url);
    const cur = readFileSync(here, 'utf8');
    const open = cur.indexOf('export const EXPECTED_UNITS = {');
    const close = cur.indexOf('\n};', open);
    if (open < 0 || close < 0)
        throw new Error(
            'expected-counts.mjs: cannot find the EXPECTED_UNITS block to splice',
        );

    const rows = (o, indent) =>
        Object.entries(o)
            .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
            .map(([k, v]) => `${indent}${JSON.stringify(k)}: ${v.units ?? v},`)
            .join('\n');

    const block =
        'export const EXPECTED_UNITS = {\n' +
        '    // Files #6385 touches, read at BASE: doc/md/**, doc/overview-slides.md, samples/**, src/prelude/**.\n' +
        '    oracle: {\n' +
        rows(oracle, '        ') +
        '\n    },\n' +
        '    // Every .mo and every motoko fence in the repo at BASE, including test/**.\n' +
        '    full: {\n' +
        rows(full, '        ') +
        '\n    },\n' +
        '};';

    // `close` points at the `\n` before the block's closing `};`; resuming at `close + 3` keeps that
    // `};` out of the tail (the emitted block already ends with it), so the output round-trips exactly.
    writeFileSync(here, cur.slice(0, open) + block + cur.slice(close + 3));
    return {
        oracle: Object.keys(oracle).length,
        full: Object.keys(full).length,
    };
}
